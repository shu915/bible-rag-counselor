// 他人を傷つけたい気持ちを示す語が含まれていれば true
export function detectHarmToOthers(text: string): boolean {
  const normalized = normalizeForCrisis(text);
  return NORMALIZED_HARM_PHRASES.some((phrase) => normalized.includes(phrase));
}

