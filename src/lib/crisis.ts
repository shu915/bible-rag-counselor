// 命の危険を示す入力を、AI を呼ぶ前に、単純なキーワードで検出する(docs/safety.md の「1」)。
// 見逃しは必ず出る。誤検知は許す(広めにする。固定画面に「それでも続ける」の選択肢がある)。
// AI の成否や、回数制限に依存させない。検出した入力は、保存しない・ログに出さない。検出の有無も、記録しない。
// 語のリストは、人が作る。変えたときの挙動が分かるように、crisis.test.ts に、検出すべき/すべきでない例を固定する。
//
// 方針:
// - 語は、活用形に強くするため、語幹で止める(「死にたい」「死にたくなる」「死にたかった」を、「死にた」で拾う)
// - 漢字の語は、**ひらがな版も持つ**(正規化で効くのは、カタカナ → ひらがなだけ。「しんでしまいたい」は、別に要る)
// - 広げすぎない: 「死んでしま」だけを語幹にすると、「大切な人が死んでしまった」(死別の相談。このアプリの大事な相談)を
//   誤検知する。「死んでしまいたい」「死んでしまえ」「死んでしまおう」のように、**先を足した形**で拾う(「しまった」は避ける)
// - 単独では広すぎる語(「しんどい」「飛び込み」「行きたい」)は、単独で入れない。「飛び込み営業がつらい」「しんどい」を、
//   誤検知しないため。「生きるのがしんどい」「電車に飛び込みたい」のように、文脈つきの形で入れる

// 比べやすいように、全角・半角をそろえ(NFKC)、カタカナをひらがなにして、空白・記号・書式文字(ゼロ幅スペースなど)を除く
export function normalizeForCrisis(text: string): string {
  return text
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60))
    .replace(/[\s\p{P}\p{S}\p{Cf}\p{Cc}]/gu, "");
}

