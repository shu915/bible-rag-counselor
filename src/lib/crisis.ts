// 語だけでは、誤検知が多いもの(正規表現で、除外を付ける)
const CRISIS_PATTERNS: readonly RegExp[] = [
  // 「もう死ぬ」だが、「もう死ぬほど疲れた」「死ぬ気で」は除く
  /もう死ぬ(?!ほど|気)/,
  /もうしぬ(?!ほど|き)/,
  // 隠語の「OD」(過量服薬)。英単語(good・mod など)の中の od は、除く
  /(?<![a-z])od(?![a-z])/,
];

const NORMALIZED_PHRASES = CRISIS_PHRASES.map(normalizeForCrisis);

// 命の危険を示す語が含まれていれば true
export function detectCrisis(text: string): boolean {
  const normalized = normalizeForCrisis(text);
  return (
    NORMALIZED_PHRASES.some((phrase) => normalized.includes(phrase)) ||
    CRISIS_PATTERNS.some((pattern) => pattern.test(normalized))
  );
}

