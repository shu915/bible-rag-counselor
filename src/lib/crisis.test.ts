describe("detectCrisis(検出しない)", () => {
  it.each([
    "仕事で疲れ果てて、もう限界だ",
    "明日のことが心配で、夜も眠れない",
    "SNSで他の人と比べてしまって、落ち込む",
    "死ぬほど忙しい",
    "親友に裏切られて、人を信じられなくなった",
    "",
    // 死別の相談は、誤検知しない(「死んでしま」を、語幹にしない理由)
    "大切な人が死んでしまった",
    "愛犬が死んでしまって、悲しい",
    // 人を傷つけた懺悔
    "友達を傷つけてしまった",
    // 慣用句・英単語・ふつうの「消えた」
    "もう死ぬほど疲れた",
    "死ぬ気で頑張ったのに、報われない",
    "good morning",
    "停電で電気が消えた",
    "データが消えた",
    // 「自分」つきだけ拾う(他人への言葉は、拾わない)。「死ねばいい」「死ぬ」単独は、広すぎるので、入れていない
    "あの人がいないほうがいい",
    // 単独では広すぎる語は、入れていない(文脈つきの形だけ)
    "飛び込み営業がつらい",
    "仕事がしんどい",
    "ごはんを食べに行きたい",
    "死ぬほど疲れた",
    "mod を入れた。goodluck",
  ])("%s", (text) => {
    expect(detectCrisis(text)).toBe(false);
  });

  it("誤検知は許す方針: 比喩でも、検出する(固定画面の側で、相談を続けられるようにする)", () => {
    expect(detectCrisis("死にたいくらい恥ずかしい")).toBe(true);
  });
});

describe("normalizeForCrisis", () => {
  it("全角・半角と、カタカナ・ひらがなと、空白・記号をそろえる", () => {
    expect(normalizeForCrisis("シ ニ タ イ！")).toBe("しにたい");
    expect(normalizeForCrisis("ＡＢＣ")).toBe("abc");
  });
});

describe("detectHarmToOthers(他人を傷つけたい気持ち。自傷とは別)", () => {
  it.each([
    "あいつぶっ殺してやる",
    "上司を殺したい",
    "ころしてやる",
    "殺意がわいた",
    "あいつをぶん殴りたい",
    // 第4回のレビュー: 広げた語
    "あいつ死ねばいい",
    "死ねよ",
    "あいつに死んでほしい",
    "ぶっ飛ばしてやる",
    "ぶっ潰す",
    "痛い目に遭わせたい",
    "始末したい",
    "家に火をつけてやる",
    "あいつに復讐したい",
    "殺しに行く",
    "包丁を持った",
    "時間を殺す", // 誤検知。指示を足すだけなので、害はない
  ])("検出する: %s", (text) => {
    expect(detectHarmToOthers(text)).toBe(true);
  });

  it.each([
    "仕事で疲れ果てて、もう限界だ",
    "大切な人が死んでしまった",
    "友達を傷つけてしまった",
    "もう死にたい",
    "",
    "上司に怒られて、落ち込んでいる",
    "復讐は、神のすることだと聞いた",
  ])("検出しない: %s", (text) => {
    expect(detectHarmToOthers(text)).toBe(false);
  });

  it("自傷の検出(detectCrisis)とは、別。他害の語は、固定画面(自傷向け)にはしない", () => {
    expect(detectCrisis("あいつぶっ殺してやる")).toBe(false);
  });
});

